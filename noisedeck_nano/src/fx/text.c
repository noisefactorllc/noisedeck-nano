static const char GLYPH_KEYS[] = " !.:-/0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ<>%+=^?()abcdefghijklmnopqrstuvwxyz";

const uint8_t *text_glyph(char c) {
  for (int i = 0; GLYPH_KEYS[i]; i++)
    if (GLYPH_KEYS[i] == c) return GLYPHS[i];
  return GLYPHS[0];
}

int text_width(const char *str, int scale, int spacing) {
  int n = 0;
  while (str[n]) n++;
  if (n == 0) return 0;
  return n * TEXT_GLYPH_W * scale + (n - 1) * spacing;
}

void text_draw_band(uint16_t *out, int band_w, int y0, int band_h, const char *str, int x, int y, int scale,
                    int spacing, uint16_t color) {
  int gh = TEXT_GLYPH_H * scale;
  if (y >= y0 + band_h || y + gh <= y0) return;
  int cx = x;
  for (const char *p = str; *p; p++) {
    const uint8_t *g = text_glyph(*p);
    for (int col = 0; col < TEXT_GLYPH_W; col++) {
      uint8_t bits = g[col];
      for (int row = 0; row < TEXT_GLYPH_H; row++) {
        if (!(bits & (1u << row))) continue;
        for (int sy = 0; sy < scale; sy++) {
          int py = y + row * scale + sy;
          if (py < y0 || py >= y0 + band_h) continue;
          uint16_t *line = out + (py - y0) * band_w;
          for (int sx = 0; sx < scale; sx++) {
            int px = cx + col * scale + sx;
            if (px >= 0 && px < band_w) line[px] = color;
          }
        }
      }
    }
    cx += TEXT_GLYPH_W * scale + spacing;
  }
}
